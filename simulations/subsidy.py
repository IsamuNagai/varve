#!/usr/bin/env python3
"""Exact integer block-subsidy schedule for ADR-0004 / protocol/subsidy.md.

Generates the 64 consensus constants FRAC[k] = floor(2^63 * 2^(-k/64)), proves
each one with exact integer arithmetic, prints supply milestones, and writes
test vectors to test-vectors/subsidy.json.

Usage: python3 -I simulations/subsidy.py
"""
import json
import os
from decimal import Decimal, getcontext

LAMINAE_PER_VARVE = 100_000_000
TARGET_SPACING = 300                       # seconds
BLOCKS_PER_YEAR = 105_192                  # 365.25 days / 300 s
HALF_LIFE_BLOCKS = 8 * BLOCKS_PER_YEAR     # 841,536
EPOCHS_PER_HALF_LIFE = 64
BLOCKS_PER_EPOCH = HALF_LIFE_BLOCKS // EPOCHS_PER_HALF_LIFE   # 13,149
INITIAL_SUBSIDY = 82 * LAMINAE_PER_VARVE   # laminae
TAIL_SUBSIDY = 6 * LAMINAE_PER_VARVE       # laminae

assert HALF_LIFE_BLOCKS % EPOCHS_PER_HALF_LIFE == 0


def frac_table():
    getcontext().prec = 120
    ln2 = Decimal(2).ln()
    table = []
    for k in range(64):
        v = int((Decimal(2) ** 63 * (-(ln2 * k) / 64).exp()).to_integral_value(rounding="ROUND_FLOOR"))
        # Exact proof that v = floor(2^63 * 2^(-k/64)):
        #   v^64 * 2^k <= 2^(63*64) < (v+1)^64 * 2^k
        assert v ** 64 * 2 ** k <= 2 ** (63 * 64) < (v + 1) ** 64 * 2 ** k, k
        table.append(v)
    assert table[0] == 2 ** 63 and all(x < 2 ** 64 for x in table)
    return table


FRAC = frac_table()


def subsidy(height):
    """Block subsidy in laminae for a block at `height` (genesis = 0 pays nothing)."""
    if height == 0:
        return 0
    epoch = (height - 1) // BLOCKS_PER_EPOCH
    shift = 63 + epoch // 64
    decayed = 0 if shift >= 128 else (INITIAL_SUBSIDY * FRAC[epoch % 64]) >> shift
    return max(decayed, TAIL_SUBSIDY)


def supply_at(height):
    """Total laminae issued in blocks 1..height (fast: sums whole epochs)."""
    total, h = 0, 1
    while h <= height:
        epoch_end = ((h - 1) // BLOCKS_PER_EPOCH + 1) * BLOCKS_PER_EPOCH
        last = min(height, epoch_end)
        total += subsidy(h) * (last - h + 1)
        h = last + 1
    return total


if __name__ == "__main__":
    print("FRAC table (Q63), all 64 entries proven exact:")
    for i in range(0, 64, 4):
        print("  " + "  ".join(f"0x{FRAC[j]:016X}" for j in range(i, i + 4)))
    tail_epoch = next(e for e in range(10_000) if subsidy(e * BLOCKS_PER_EPOCH + 1) == TAIL_SUBSIDY)
    print(f"\nInitial subsidy {INITIAL_SUBSIDY / LAMINAE_PER_VARVE} varve, tail {TAIL_SUBSIDY / LAMINAE_PER_VARVE} varve,"
          f" epoch {BLOCKS_PER_EPOCH} blocks; tail reached at epoch {tail_epoch}"
          f" (block {tail_epoch * BLOCKS_PER_EPOCH + 1:,}, year {tail_epoch * BLOCKS_PER_EPOCH / BLOCKS_PER_YEAR:.1f})")
    print("\nYear | supply (varve)   | issued that year | inflation")
    prev = 0
    for y in (1, 2, 4, 8, 10, 16, 20, 30, 50, 100, 200):
        s = supply_at(y * BLOCKS_PER_YEAR)
        p = supply_at((y - 1) * BLOCKS_PER_YEAR)
        infl = f"{(s - p) / p * 100:6.2f}%" if p else "     -"
        print(f"{y:4d} | {s / LAMINAE_PER_VARVE:16,.2f} | {(s - p) / LAMINAE_PER_VARVE:16,.2f} | {infl}")
    max_supply_1000y = supply_at(1000 * BLOCKS_PER_YEAR)
    print(f"\nSupply after 1,000 years: {max_supply_1000y / LAMINAE_PER_VARVE:,.0f} varve "
          f"({max_supply_1000y / 2**63 * 100:.4f}% of 2^63 laminae)")

    heights = sorted({1, 2, BLOCKS_PER_EPOCH, BLOCKS_PER_EPOCH + 1, 2 * BLOCKS_PER_EPOCH + 1,
                      HALF_LIFE_BLOCKS, HALF_LIFE_BLOCKS + 1, 2 * HALF_LIFE_BLOCKS + 1,
                      tail_epoch * BLOCKS_PER_EPOCH, tail_epoch * BLOCKS_PER_EPOCH + 1,
                      10 * BLOCKS_PER_YEAR, 100 * BLOCKS_PER_YEAR, 2**31, 2**32 - 1})
    vectors = {
        "description": "Block subsidy test vectors (laminae). Generated by simulations/subsidy.py.",
        "constants": {"INITIAL_SUBSIDY": INITIAL_SUBSIDY, "TAIL_SUBSIDY": TAIL_SUBSIDY,
                      "BLOCKS_PER_EPOCH": BLOCKS_PER_EPOCH, "FRAC_Q63": [f"0x{x:016X}" for x in FRAC]},
        "subsidy": [{"height": 0, "subsidy": 0}] + [{"height": h, "subsidy": subsidy(h)} for h in heights],
        "cumulative_supply": [{"height": h, "supply": supply_at(h)}
                              for h in (BLOCKS_PER_YEAR, 4 * BLOCKS_PER_YEAR, 10 * BLOCKS_PER_YEAR, 50 * BLOCKS_PER_YEAR)],
    }
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "test-vectors", "subsidy.json")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        json.dump(vectors, fh, indent=1)
        fh.write("\n")
    print(f"\nWrote {len(vectors['subsidy'])} subsidy vectors to test-vectors/subsidy.json")
